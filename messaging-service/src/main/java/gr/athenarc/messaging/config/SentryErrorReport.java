package gr.athenarc.messaging.config;

import io.sentry.Sentry;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ControllerAdvice;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.reactive.result.method.annotation.ResponseEntityExceptionHandler;
import org.springframework.web.server.*;
import reactor.core.publisher.Mono;

@ControllerAdvice
public class SentryErrorReport extends ResponseEntityExceptionHandler {

    @ExceptionHandler(Exception.class)
    public Mono<ResponseEntity<Object>> handle(Exception ex, ServerWebExchange exchange) {
        Sentry.captureException(ex);
        return super.handleException(ex, exchange);
    }
}
